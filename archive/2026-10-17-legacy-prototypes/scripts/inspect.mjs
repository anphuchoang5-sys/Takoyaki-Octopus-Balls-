import {chromium} from 'playwright';
import {mkdir,writeFile} from 'node:fs/promises';
await mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
const response=await page.goto(process.argv[2]||'http://127.0.0.1:4173',{waitUntil:'networkidle'});
await page.waitForFunction(()=>window.__rainyCorner?.ready,{timeout:60000});
await page.screenshot({path:'artifacts/01-overview.png'});
const start=await page.evaluate(()=>({camera:window.__rainyCorner.camera,frames:window.__rainyCorner.frames,stats:window.__rainyCorner.stats,doorGap:window.__rainyCorner.doorGap,elapsed:window.__rainyCorner.elapsed}));
await page.mouse.move(760,570);await page.mouse.down();await page.mouse.move(1050,610,{steps:18});await page.mouse.up();
await page.waitForTimeout(600);
const rotated=await page.evaluate(()=>window.__rainyCorner.camera);
await page.screenshot({path:'artifacts/02-rotated.png'});
await page.locator('canvas#world').focus();await page.keyboard.press('Home');
await page.mouse.wheel(0,-650);await page.waitForTimeout(600);
const zoomed=await page.evaluate(()=>window.__rainyCorner.camera);
await page.screenshot({path:'artifacts/03-closeup.png'});
await page.setViewportSize({width:430,height:932});await page.keyboard.press('Home');await page.waitForTimeout(600);
await page.screenshot({path:'artifacts/04-mobile.png'});
const mobileCamera=await page.evaluate(()=>window.__rainyCorner.camera);
await page.setViewportSize({width:1440,height:1100});await page.keyboard.press('Home');
for(let i=0;i<27;i++)await page.keyboard.press('ArrowRight');
await page.screenshot({path:'artifacts/05-back.png'});
await page.keyboard.press('Home');
await page.waitForFunction(()=>window.__rainyCorner.doorGap>2.3,{timeout:26000});
const doorOpen=await page.evaluate(()=>({gap:window.__rainyCorner.doorGap,time:window.__rainyCorner.elapsed}));
await page.screenshot({path:'artifacts/06-door-open.png'});
await page.waitForFunction(()=>window.__rainyCorner.doorGap<.9,{timeout:12000});
const doorClosed=await page.evaluate(()=>({gap:window.__rainyCorner.doorGap,time:window.__rainyCorner.elapsed}));
const end=await page.evaluate(()=>({frames:window.__rainyCorner.frames,doorGap:window.__rainyCorner.doorGap,elapsed:window.__rainyCorner.elapsed,bodyChildren:[...document.body.children].map(e=>({tag:e.tagName,visible:getComputedStyle(e).display!=='none'&&e.tagName!=='SCRIPT'}))}));
const report={httpStatus:response.status(),errors,start,rotated,zoomed,mobileCamera,doorOpen,doorClosed,end,rotationChanged:JSON.stringify(rotated)!==JSON.stringify(start.camera),zoomChanged:JSON.stringify(zoomed)!==JSON.stringify(start.camera),animationAdvanced:end.frames>start.frames};
await writeFile('artifacts/inspection.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
await browser.close();
