// Offline authoring step: reuse the editor's original model renderer and camera.
import {chromium} from 'playwright';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const check=process.argv.includes('--check'),dir='dist/town/editor/thumbnails';
const hash=b=>createHash('sha256').update(b).digest('hex');
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const sources={},errors=[];
try{
 const page=await browser.newPage({viewport:{width:1280,height:800},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 const html=await readFile('dist/index.html','utf8'),importmap=html.match(/<script type="importmap">[\s\S]*?<\/script>/)[0];
 await page.route('**/*',async route=>{
  const url=new URL(route.request().url());assert.equal(url.origin,'http://127.0.0.1:4173');
  if(url.pathname==='/__thumbnails')return route.fulfill({contentType:'text/html',body:`<!doctype html><meta charset="UTF-8">${importmap}`});
  if(url.pathname.endsWith('.js')&&!url.pathname.startsWith('/vendor/')){
   const source=await readFile('dist'+url.pathname);sources['dist'+url.pathname]=hash(source);
   return route.fulfill({contentType:'text/javascript',body:source});
  }
  return route.continue();
 });
 await page.goto('http://127.0.0.1:4173/__thumbnails');
 const results=await page.evaluate(async()=>{
  const {renderThumbnails}=await import('/town/editor/scene.js'),{ASSETS,createAsset,TILE_SIZE}=await import('/town/editor/catalog.js');
  const images=renderThumbnails(ASSETS,createAsset,TILE_SIZE);
  return ASSETS.map(a=>({id:a.id,revision:a.revision??null,data:images.get(a.id)}));
 });
 assert.deepEqual(errors,[]);assert(results.length>0);
 const entries=[];if(!check)await mkdir(dir,{recursive:true});
 for(const {id,revision,data}of results){
  assert(/^[a-z0-9-]+$/.test(id));assert(data.startsWith('data:image/png;base64,'));
  const png=Buffer.from(data.split(',')[1],'base64'),file=`${id}.png`;
  if(check)assert.equal(hash(await readFile(`${dir}/${file}`)),hash(png),`Stale thumbnail: ${id}; run node scripts/generate-editor-thumbnails.mjs`);
  else await writeFile(`${dir}/${file}`,png);
  entries.push({id,revision,file,sha256:hash(png),bytes:png.length});
 }
 const module='// Generated by scripts/generate-editor-thumbnails.mjs. Keep the original 280 x 190 rendering.\n'+
  'export const editorThumbnails = new Map([\n'+entries.map(e=>`  ['${e.id}', new URL('./thumbnails/${e.file}', import.meta.url).href]`).join(',\n')+'\n]);\n';
 if(check)assert.equal(await readFile('dist/town/editor/thumbnails.js','utf8'),module,'Catalog coverage changed; regenerate thumbnails');
 else{
  await writeFile('dist/town/editor/thumbnails.js',module);
  await writeFile(`${dir}/manifest.json`,JSON.stringify({width:280,height:190,entries,sources},null,2)+'\n');
 }
 console.log(JSON.stringify({mode:check?'check':'generate',count:entries.length,pngBytes:entries.reduce((n,e)=>n+e.bytes,0),errors}));
}finally{await browser.close();}
